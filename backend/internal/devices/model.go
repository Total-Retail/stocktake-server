// Package devices lets several counters share one counting device.
//
// 13 Oct 2026 (Wyne) — not every counter can be given a device. A supervisor enrols a
// device for shared counting (it then holds a device token instead of a counter's
// token), and each counter carries an NFC card linked to them. A counter taps their
// card on the device to start counting; every count line and bin submission made
// while they are tapped in carries their counter id, the device id and the method
// ("NFC"), so the variance, audit and performance reports still say who counted
// what, and on which device.
//
// Trust model: the device is trusted (a supervisor enrolled it and can revoke it);
// the card says who is holding the device. A card's UID is an identifier, not a
// secret — it can be read by any phone — so this is attribution, not strong
// authentication. Cards with a cryptographic tap (NTAG 424 DNA SUN messages) would
// be the upgrade if that ever matters.
package devices

import "time"

// AuthMethod says how the counter on a count line was identified.
const (
	AuthOTP = "OTP" // the counter signed in on the device with their phone and an SMS code
	AuthNFC = "NFC" // the counter tapped their card on a shared device
)

// Device is a counting device enrolled for shared (NFC card) counting.
type Device struct {
	ID string `json:"id" gorm:"type:uuid;primaryKey;default:gen_random_uuid()"`
	// Name is what supervisors call it ("Zebra TC21 #3").
	Name string `json:"name" gorm:"not null"`
	// InstallID is generated by the app on first run; enrolling the same install again
	// re-uses the row (and invalidates the old token).
	InstallID string `json:"install_id" gorm:"type:text;uniqueIndex;not null"`
	// StoreID, when set, limits the device's roster to counters on that store's counts.
	StoreID    *string `json:"store_id" gorm:"type:uuid;index"`
	Model      string  `json:"model"`
	AppVersion string  `json:"app_version"`
	Active     bool    `json:"active" gorm:"not null;default:true"`
	// TokenVersion is in the device token; bumping it (re-enrol, revoke) kills old tokens.
	TokenVersion int        `json:"-" gorm:"not null;default:1"`
	EnrolledBy   string     `json:"enrolled_by" gorm:"type:uuid;not null"`
	EnrolledAt   time.Time  `json:"enrolled_at" gorm:"not null;default:now()"`
	RevokedAt    *time.Time `json:"revoked_at"`
	RevokedBy    *string    `json:"revoked_by" gorm:"type:uuid"`
	LastSeenAt   *time.Time `json:"last_seen_at"`
}

func (Device) TableName() string { return "devices" }

// CounterTag links an NFC card (its UID) to a counter. A card belongs to at most one
// counter and a counter has at most one active card (partial unique indexes, see
// EnsureIndexes); unlinking keeps the row for the audit trail.
type CounterTag struct {
	ID         string     `json:"id" gorm:"type:uuid;primaryKey;default:gen_random_uuid()"`
	CounterID  string     `json:"counter_id" gorm:"type:uuid;not null;index"`
	UID        string     `json:"uid" gorm:"column:uid;type:varchar(32);not null;index"`
	Label      string     `json:"label"`
	Active     bool       `json:"active" gorm:"not null;default:true"`
	AssignedBy string     `json:"assigned_by" gorm:"type:uuid;not null"`
	AssignedAt time.Time  `json:"assigned_at" gorm:"not null;default:now()"`
	RevokedAt  *time.Time `json:"revoked_at"`
	RevokedBy  *string    `json:"revoked_by" gorm:"type:uuid"`
	LastUsedAt *time.Time `json:"last_used_at"`
}

func (CounterTag) TableName() string { return "counter_tags" }

// CounterWithTag is a counter as the admin screens list it: with its active card, if any.
type CounterWithTag struct {
	ID             string     `json:"id"`
	Name           string     `json:"name"`
	MobileNumber   string     `json:"mobile_number"`
	CanPrintLabels bool       `json:"can_print_labels"`
	CreatedAt      time.Time  `json:"created_at"`
	TagUID         *string    `json:"tag_uid"`
	TagLabel       *string    `json:"tag_label"`
	TagAssignedAt  *time.Time `json:"tag_assigned_at"`
	TagLastUsedAt  *time.Time `json:"tag_last_used_at"`
}

// DeviceView is a device as the admin portal lists it.
type DeviceView struct {
	Device
	StoreName      *string `json:"store_name"`
	EnrolledByName *string `json:"enrolled_by_name"`
}

// RosterEntry is one counter a shared device may identify offline: the card, the
// counter and the sessions they are on.
type RosterEntry struct {
	CounterID    string   `json:"counter_id"`
	Name         string   `json:"name"`
	MobileNumber string   `json:"mobile_number"`
	TagUID       string   `json:"tag_uid"`
	TagLabel     string   `json:"tag_label"`
	SessionIDs   []string `json:"session_ids"`
	// CanPrintLabels: the counter may use Label Printing (then SessionIDs may be empty).
	CanPrintLabels bool `json:"can_print_labels"`
}
